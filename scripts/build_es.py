#!/usr/bin/env python3
"""Generate the static Spanish page (es/index.html) from index.html.

index.html is the single source of truth. Translations live next to the English
text as attributes:

  data-es="..."         replaces the element's inner HTML
  data-es-<attr>="..."  replaces <attr> (e.g. data-es-href, data-es-content, data-es-placeholder)

Run after every change to index.html:

  python3 scripts/build_es.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "index.html"
OUT = ROOT / "es" / "index.html"

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
ATTR = r'(?:\s+[^\s=>/"\']+(?:\s*=\s*(?:"[^"]*"|\'[^\']*\'|[^\s>"\']+))?)'
TAG = re.compile(r'<(/?)([a-zA-Z][a-zA-Z0-9-]*)(' + ATTR + r'*)\s*(/?)>')
ATTR_ONE = re.compile(r'\s+([^\s=>/"\']+)(?:\s*=\s*("([^"]*)"|\'([^\']*)\'|([^\s>"\']+)))?')


def parse_attrs(s):
    attrs = []
    for m in ATTR_ONE.finditer(s):
        val = m.group(3) if m.group(3) is not None else m.group(4) if m.group(4) is not None else m.group(5)
        attrs.append([m.group(1), val])
    return attrs


def render_attrs(attrs):
    out = ""
    for name, val in attrs:
        out += f" {name}" if val is None else f' {name}="{val}"'
    return out


def translate_tag(attrs):
    """Apply data-es-* attribute overrides and drop all data-es* attributes."""
    overrides = {n[len("data-es-"):]: v for n, v in attrs if n.startswith("data-es-")}
    inner = next((v for n, v in attrs if n == "data-es"), None)
    kept = [[n, overrides.pop(n, v)] for n, v in attrs if not n.startswith("data-es")]
    kept += [[n, v] for n, v in overrides.items()]  # attributes that only exist in Spanish
    return kept, inner


def find_close(html, name, pos):
    """Return (start, end) of the closing tag that matches an element opened before pos."""
    depth = 1
    for m in TAG.finditer(html, pos):
        if m.group(2).lower() != name:
            continue
        if m.group(1):
            depth -= 1
            if depth == 0:
                return m.start(), m.end()
        elif not m.group(4):
            depth += 1
    raise ValueError(f"unclosed <{name}> at {pos}")


def build(html):
    out, pos = [], 0
    while True:
        m = TAG.search(html, pos)
        if not m:
            out.append(html[pos:])
            break
        out.append(html[pos:m.start()])
        closing, name, attr_str, selfclose = m.group(1), m.group(2).lower(), m.group(3), m.group(4)
        if closing or "data-es" not in attr_str:
            out.append(m.group(0))
            pos = m.end()
            if not closing and name in ("script", "style"):
                end = html.index(f"</{name}>", pos)
                out.append(html[pos:end])
                pos = end
            continue
        attrs, inner = translate_tag(parse_attrs(attr_str))
        out.append(f"<{m.group(2)}{render_attrs(attrs)}{' /' if selfclose else ''}>")
        pos = m.end()
        if inner is not None and name not in VOID and not selfclose:
            cstart, cend = find_close(html, name, pos)
            out.append(inner)
            out.append(html[cstart:cend])
            pos = cend
    return "".join(out)


def main():
    html = build(SRC.read_text(encoding="utf-8"))
    # es/ lives one level down, so local assets need ../
    html = re.sub(r'((?:src|href)=["\']|url\([\'"]?)assets/', r"\1../assets/", html)
    # Comment goes after the doctype; anything before it triggers quirks mode
    doctype, rest = html.split("\n", 1)
    html = f"{doctype}\n<!-- Generated by scripts/build_es.py from index.html. Do not edit by hand. -->\n{rest}"
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
